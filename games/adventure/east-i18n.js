let current = 'ru';

export function setLanguage(language) {
  current = language === 'en' ? 'en' : 'ru';
  return current;
}

export function getLanguage() {
  return current;
}

export function isEnglish() {
  return current === 'en';
}

export function pick(value, vars = {}) {
  if (value == null) return '';
  let text;
  if (typeof value === 'string') text = value;
  else text = value[current] ?? value.ru ?? value.en ?? '';
  return interpolate(String(text), vars);
}

export function t(key, vars = {}) {
  const table = STRINGS[current] || STRINGS.ru;
  const value = table[key] ?? STRINGS.ru[key] ?? key;
  return interpolate(value, vars);
}

function interpolate(text, vars) {
  return text.replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  ));
}

export function translateDocument(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) {
    node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
  }
  for (const node of root.querySelectorAll('[data-i18n-aria]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nAria));
  }
  for (const node of root.querySelectorAll('[data-i18n-title]')) {
    node.setAttribute('title', t(node.dataset.i18nTitle));
  }
  document.documentElement.lang = current;
}

export function languageName(language = current) {
  return language === 'en' ? 'English' : 'Русский';
}
